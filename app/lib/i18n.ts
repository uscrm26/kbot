// 語音引擎選擇，browser 為瀏覽器原生，doubao 為豆包流式識別
export type SpeechEngine = 'browser' | 'doubao';

export function getSpeechEngine(): SpeechEngine {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('bolt-speech-engine');
    if (saved === 'browser' || saved === 'doubao') return saved;
  }
  return 'browser';
}

export function setSpeechEngine(engine: SpeechEngine): void {
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('bolt-speech-engine', engine);
  }
}
